# trainer_manager.py
import requests
import json
import time
from datetime import datetime

class BotTrainerManager:
    def __init__(self, telegram_token):
        self.telegram_token = telegram_token
        self.base_url = f"https://api.telegram.org/bot{telegram_token}"
        self.training_log = []
        
    def send_training_message(self, chat_id, message):
        """Отправляет обучающее сообщение боту"""
        url = f"{self.base_url}/sendMessage"
        payload = {
            "chat_id": chat_id,
            "text": message,
            "parse_mode": "Markdown"
        }
        
        try:
            response = requests.post(url, json=payload, timeout=10)
            if response.status_code == 200:
                log_entry = f"✅ [{datetime.now()}] Отправлено: {message[:80]}..."
                print(log_entry)
                self.training_log.append(log_entry)
                return True
            else:
                error_msg = f"❌ Ошибка {response.status_code}: {response.text}"
                print(error_msg)
                self.training_log.append(error_msg)
                return False
        except Exception as e:
            error_msg = f"❌ Исключение: {str(e)}"
            print(error_msg)
            self.training_log.append(error_msg)
            return False
    
    def start_basic_training(self, chat_id):
        """Запускает базовое обучение"""
        print("🚀 НАЧИНАЮ БАЗОВОЕ ОБУЧЕНИЕ БОТА...")
        
        training_modules = [
            self.module_anxiety_techniques(chat_id),
            self.module_depression_techniques(chat_id), 
            self.module_communication_patterns(chat_id),
            self.module_crisis_responses(chat_id)
        ]
        
        for module in training_modules:
            for message in module:
                self.send_training_message(chat_id, message)
                time.sleep(2)  # Пауза между сообщениями
                
        print("🎉 БАЗОВОЕ ОБУЧЕНИЕ ЗАВЕРШЕНО!")
        self.save_training_log()
    
