            "• *Техника:* Повторяй слова партнера: 'Правильно ли я понимаю, что ты чувствуешь...?'\n"
            "• *Когда использовать:* конфликты, недопонимание, эмоциональные разговоры\n"
            "• *Эффект:* Показывает что ты действительно слышишь партнера\n"
            "• *Ошибка избегать:* Перебивание, советы без запроса, обесценивание",

            # Навык 2
            "👂 *НАВЫК: Я-СООБЩЕНИЯ*\n\n"  
            "• *Формат:* 'Я чувствую X, когда ты делаешь Y, потому что Z'\n"
